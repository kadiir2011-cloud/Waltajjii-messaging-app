const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const sqlite = fs.readFileSync(path.join(root, "src/db.js"), "utf8");
const postgres = fs.readFileSync(path.join(root, "migrations/postgres/001_initial_schema.sql"), "utf8");

const expectedTables = [
  "users", "messages", "groups", "group_members", "group_messages",
  "follows", "connection_requests", "posts", "post_likes", "post_comments",
  "notifications", "channels", "channel_members", "channel_messages", "moments",
  "message_reactions", "message_hidden_for", "group_message_reactions",
  "group_message_receipts", "group_invitations", "group_invitation_events",
  "group_join_requests", "group_activity", "group_polls", "group_poll_options",
  "group_poll_votes", "group_events", "group_event_rsvps",
  "group_event_reminder_deliveries"
];

function tableNames(source) {
  return [...source.matchAll(/CREATE TABLE IF NOT EXISTS\s+([a-z_][a-z0-9_]*)/gi)]
    .map(match => match[1].toLowerCase());
}

function pgTableBlock(name) {
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const match = postgres.match(new RegExp(
    `CREATE TABLE IF NOT EXISTS\\s+${escaped}\\s*\\(([\\s\\S]*?)\\n\\);`,
    "i"
  ));
  assert.ok(match, `PostgreSQL table definition missing: ${name}`);
  return match[1];
}

test("SQLite and PostgreSQL definitions cover the complete 29-table inventory", () => {
  const sqliteNames = new Set(tableNames(sqlite));
  const pgNames = new Set(tableNames(postgres));
  for (const name of expectedTables) {
    assert.ok(sqliteNames.has(name), `SQLite source table missing: ${name}`);
    assert.ok(pgNames.has(name), `PostgreSQL table missing: ${name}`);
  }
  assert.equal(expectedTables.length, 29);
});

test("PostgreSQL identity primary keys are used for all standalone integer-ID entities", () => {
  const identityTables = [
    "users", "messages", "groups", "group_messages", "connection_requests",
    "posts", "post_comments", "notifications", "channels", "channel_messages",
    "moments", "group_invitations", "group_invitation_events",
    "group_join_requests", "group_activity", "group_polls",
    "group_poll_options", "group_events"
  ];
  for (const name of identityTables) {
    const block = pgTableBlock(name);
    assert.match(block, /id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/i, name);
  }
});

test("later-added SQLite application fields are represented in PostgreSQL", () => {
  const required = {
    users: ["professional_title", "organization", "department", "location", "website", "profile_mode", "full_name", "profile_background"],
    messages: ["delivered_at", "read_at", "reply_to_message_id", "edited_at", "deleted_at", "deleted_by", "forwarded_from_username"],
    groups: ["description", "rules", "visibility", "approval_required", "member_list_visibility"],
    group_messages: ["media_path", "media_type", "reply_to_message_id", "edited_at", "deleted_at", "is_announcement", "pinned_at", "pinned_by"]
  };
  for (const [table, columns] of Object.entries(required)) {
    const block = pgTableBlock(table);
    for (const column of columns) {
      assert.match(block, new RegExp(`\\b${column}\\b`, "i"), `${table}.${column}`);
    }
  }
});

test("timestamp contract uses TIMESTAMPTZ and UTC-based Moments expiry", () => {
  assert.match(postgres, /created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP/i);
  assert.match(postgres, /expires_at TIMESTAMPTZ NOT NULL DEFAULT \(CURRENT_TIMESTAMP \+ INTERVAL '24 hours'\)/i);
  assert.match(postgres, /starts_at TIMESTAMPTZ NOT NULL/i);
});

test("username case-insensitive uniqueness and poll same-parent integrity are explicit", () => {
  assert.match(sqlite, /username TEXT NOT NULL COLLATE NOCASE UNIQUE/i);
  assert.match(postgres, /UNIQUE INDEX IF NOT EXISTS users_username_lower_uq ON users \(LOWER\(username\)\)/i);
  assert.match(postgres, /UNIQUE \(poll_id,id\)/i);
  assert.match(postgres, /FOREIGN KEY \(poll_id,option_id\)\s+REFERENCES group_poll_options\(poll_id,id\)/i);
});

test("legacy group receipt backfill is present in source and called out for migration review", () => {
  assert.match(sqlite, /INSERT OR IGNORE INTO group_message_receipts/i);
  assert.match(sqlite, /if \(!groupReceiptTableExists\)/i);
  const audit = fs.readFileSync(path.join(root, "PHASE-41-POSTGRESQL-SCHEMA-RECONCILIATION.md"), "utf8");
  assert.match(audit, /Historical group receipts/i);
  assert.match(audit, /identity sequence/i);
  assert.match(audit, /Unicode username/i);
});

test("draft schema is isolated and remains a non-executed migration artifact", () => {
  assert.match(postgres, /CREATE SCHEMA IF NOT EXISTS waltajjii/i);
  assert.match(postgres, /BEGIN;/i);
  assert.match(postgres, /COMMIT;/i);
  assert.match(postgres, /group_poll_votes_option_same_poll_fk/i);
});
