"use strict";

const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { Pool } = require("pg");
const { createPostgresAdapter } = require("../src/db/postgres-adapter");
const { createPostgresMediaStorageService } = require("../src/services/postgres-media-storage-service");

const connectionString = process.env.TEST_DATABASE_URL;
if (!connectionString) throw new Error("TEST_DATABASE_URL must point only to disposable CI PostgreSQL.");
const schema = "waltajjii_phase60_" + process.pid;
const pool = new Pool({ connectionString, max: 4, options: "-c search_path=" + schema });
const db = createPostgresAdapter(pool);
let storageRemovals = [];
let failNextRemoval = false;
const storageClient = {
  from(bucket) {
    return {
      remove: async keys => {
        if (failNextRemoval) {
          failNextRemoval = false;
          return { error: new Error("temporary storage outage") };
        }
        storageRemovals.push({ bucket, keys });
        return { error: null };
      }
    };
  }
};
const media = createPostgresMediaStorageService({ db, storageClient });

test("Phase 60: shared message attachments remain until every live reference is removed, then cleanup retries safely", async () => {
  await pool.query("CREATE SCHEMA " + schema);
  await pool.query("CREATE TABLE media_objects(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,bucket TEXT NOT NULL,object_key TEXT NOT NULL,purpose TEXT NOT NULL,deleted_at TIMESTAMPTZ)");
  await pool.query("CREATE TABLE messages(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,media_path TEXT,deleted_at TIMESTAMPTZ)");
  await pool.query("CREATE TABLE group_messages(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,media_path TEXT,deleted_at TIMESTAMPTZ)");
  await pool.query("CREATE TABLE channel_messages(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,media_path TEXT,deleted_at TIMESTAMPTZ)");
  await pool.query("CREATE TABLE moments(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,media_path TEXT,expires_at TIMESTAMPTZ)");
  await pool.query(fs.readFileSync(path.join(__dirname, "..", "migrations/postgres/004_media_storage_cleanup.sql"), "utf8"));
  const { rows: [object] } = await pool.query("INSERT INTO media_objects(bucket,object_key,purpose) VALUES('waltajjii-media','owner/attachment.png','message') RETURNING id");
  const id = String(object.id);
  const first = await pool.query("INSERT INTO messages(media_path) VALUES($1) RETURNING id", [id]);
  await pool.query("INSERT INTO messages(media_path) VALUES($1)", [id]);

  const stillUsed = await media.removeIfUnreferenced(id);
  assert.equal(stillUsed.reason, "still-referenced");
  assert.equal(storageRemovals.length, 0);
  assert.equal((await pool.query("SELECT deleted_at FROM media_objects WHERE id=$1", [id])).rows[0].deleted_at, null);

  await pool.query("UPDATE messages SET media_path=NULL WHERE id=$1", [first.rows[0].id]);
  assert.equal((await media.removeIfUnreferenced(id)).reason, "still-referenced");
  await pool.query("UPDATE messages SET media_path=NULL WHERE media_path=$1", [id]);

  failNextRemoval = true;
  const queued = await media.removeIfUnreferenced(id);
  assert.equal(queued.queued, true);
  assert.equal(queued.cleanupPending, true);
  const pending = (await pool.query("SELECT attempts,last_error,claimed_at FROM media_storage_cleanup WHERE media_id=$1", [id])).rows[0];
  assert.equal(pending.attempts, 1);
  assert.match(pending.last_error, /temporary storage outage/);
  assert.equal(pending.claimed_at, null);
  assert.ok((await pool.query("SELECT deleted_at FROM media_objects WHERE id=$1", [id])).rows[0].deleted_at);

  const retried = await media.processCleanupQueue(10);
  assert.deepEqual(retried, { claimed: 1, removed: 1, failed: 0 });
  assert.equal((await pool.query("SELECT COUNT(*)::int AS count FROM media_storage_cleanup WHERE media_id=$1", [id])).rows[0].count, 0);
  assert.deepEqual(storageRemovals, [{ bucket: "waltajjii-media", keys: ["owner/attachment.png"] }]);
});

test("Phase 60: group, channel, and active Moment references also prevent cleanup", async () => {
  const { rows: [object] } = await pool.query("INSERT INTO media_objects(bucket,object_key,purpose) VALUES('waltajjii-media','owner/shared.png','message') RETURNING id");
  const id = String(object.id);
  for (const table of ["group_messages", "channel_messages"]) {
    await pool.query("INSERT INTO " + table + "(media_path) VALUES($1)", [id]);
    assert.equal((await media.removeIfUnreferenced(id)).reason, "still-referenced");
    await pool.query("UPDATE " + table + " SET media_path=NULL WHERE media_path=$1", [id]);
  }
  await pool.query("INSERT INTO moments(media_path,expires_at) VALUES($1,CURRENT_TIMESTAMP + INTERVAL '1 hour')", [id]);
  assert.equal((await media.removeIfUnreferenced(id)).reason, "still-referenced");
});

test.after(async () => {
  try { await pool.query("DROP SCHEMA IF EXISTS " + schema + " CASCADE"); } catch {}
  await pool.end();
});
