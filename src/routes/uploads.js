const express = require("express");
const multer = require("multer");
const jwt = require("jsonwebtoken");
const path = require("path");
const fs = require("fs");
const crypto = require("crypto");
const db = require("../db");

const router = express.Router();

// Keep uploaded media on the same persistent disk as the SQLite database on Render.\n// Locally, retain the existing project uploads directory.\nconst uploadDir = process.env.STORAGE_DIR\n  ? path.join(process.env.STORAGE_DIR, "uploads")\n  : path.join(__dirname, "..", "..", "uploads");
fs.mkdirSync(uploadDir, { recursive: true });

const MAX_FILE_SIZE = 10 * 1024 * 1024; // 10 MB

function authenticate(req, res, next) {
  const header = req.headers.authorization || "";
  const [scheme, token] = header.split(" ");

  if (scheme !== "Bearer" || !token) {
    return res.status(401).json({ error: "Login required." });
  }

  try {
    req.auth = jwt.verify(token, process.env.JWT_SECRET, {
      issuer: "waltajjii",
      audience: "waltajjii-users"
    });
    next();
  } catch {
    return res.status(401).json({ error: "Invalid or expired login token." });
  }
}

const allowedTypes = {
  // Images
  "image/jpeg": ".jpg",
  "image/png": ".png",
  "image/webp": ".webp",
  "image/gif": ".gif",

  // Videos
  "video/mp4": ".mp4",
  "video/webm": ".webm",

  // Documents
  "application/pdf": ".pdf",
  "application/msword": ".doc",
  "application/vnd.openxmlformats-officedocument.wordprocessingml.document": ".docx",

  // Spreadsheets
  "application/vnd.ms-excel": ".xls",
  "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet": ".xlsx",
  "text/csv": ".csv",

  // Presentations
  "application/vnd.ms-powerpoint": ".ppt",
  "application/vnd.openxmlformats-officedocument.presentationml.presentation": ".pptx",

  // Text files
  "text/plain": ".txt"
};
const storage = multer.diskStorage({
  destination: (req, file, cb) => cb(null, uploadDir),
  filename: (req, file, cb) => {
    const extension = allowedTypes[file.mimetype];
    if (!extension) {
      return cb(new Error("Unsupported file type. Please select a supported image, video, or document."));
    }

    cb(null, crypto.randomUUID() + extension);
  }
});

const upload = multer({
  storage,
  limits: {
    fileSize: MAX_FILE_SIZE,
    files: 1
  },
  fileFilter: (req, file, cb) => {
    if (!Object.prototype.hasOwnProperty.call(allowedTypes, file.mimetype)) {
      return cb(new Error("Unsupported file type."));
    }
    cb(null, true);
  }
});

router.post("/", authenticate, (req, res) => {
  upload.single("media")(req, res, (err) => {
    if (err) {
      const message = err.code === "LIMIT_FILE_SIZE"
        ? "File is too large. Maximum size is 10 MB."
        : err.message || "Upload failed.";

      return res.status(400).json({ error: message });
    }

    if (!req.file) {
  return res.status(400).json({ error: "Please select a file." });
}
    const mediaType = req.file.mimetype.startsWith("image/")
  ? "image"
  : req.file.mimetype.startsWith("video/")
    ? "video"
    : "document";

 res.status(201).json({
  message: "File uploaded successfully.",
  fileId: req.file.filename,
  mediaType
});

  }); // Closes upload.single callback
}); // Closes router.post route

router.get("/:filename", authenticate, (req, res) => {
 const filename = String(req.params.filename || "");

  // Accept only filenames generated by the upload route.
  if (!/^[0-9a-f-]+\.(jpg|png|webp|gif|mp4|webm|pdf|doc|docx|xls|xlsx|ppt|pptx|txt|csv)$/i.test(filename)) {
    return res.status(400).json({ error: "Invalid media filename." });
  }

  const message = db.prepare(`
    SELECT id
    FROM messages
    WHERE media_path = ?
      AND (sender_id = ? OR receiver_id = ?)
    LIMIT 1
  `).get(filename, req.auth.userId, req.auth.userId);

  if (!message) {
    return res.status(404).json({ error: "Media not found." });
  }

  const filePath = path.join(uploadDir, filename);

  const isDocument = /\.(pdf|doc|docx|xls|xlsx|ppt|pptx|txt|csv)$/i.test(filename);

const sendOptions = isDocument
  ? { headers: { "Content-Disposition": "attachment" } }
  : {};

res.sendFile(filePath, sendOptions, (err) => {
  if (err && !res.headersSent) {
    res.status(err.statusCode === 404 ? 404 : 500).end();
  }
});

}); // Closes router.get()

module.exports = router;