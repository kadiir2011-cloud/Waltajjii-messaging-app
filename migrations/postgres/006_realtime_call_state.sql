-- Phase 104: durable, cross-instance call coordination.
-- Apply only to an isolated Waltajjii PostgreSQL staging database.
BEGIN;
CREATE SCHEMA IF NOT EXISTS waltajjii;
SET LOCAL search_path = waltajjii;

CREATE TABLE IF NOT EXISTS realtime_call_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  call_type TEXT NOT NULL CHECK (call_type IN ('direct','group')),
  group_id BIGINT REFERENCES groups(id) ON DELETE CASCADE,
  host_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','ended')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMPTZ NOT NULL,
  ended_at TIMESTAMPTZ,
  ended_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  CHECK ((call_type = 'group' AND group_id IS NOT NULL) OR
         (call_type = 'direct' AND group_id IS NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS realtime_one_active_group_call
  ON realtime_call_sessions(group_id) WHERE status = 'active' AND call_type = 'group';
CREATE INDEX IF NOT EXISTS realtime_call_sessions_expiry
  ON realtime_call_sessions(status, expires_at);

CREATE TABLE IF NOT EXISTS realtime_call_participants (
  call_id BIGINT NOT NULL REFERENCES realtime_call_sessions(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  username TEXT NOT NULL,
  participant_role TEXT NOT NULL DEFAULT 'member' CHECK (participant_role IN ('host','member')),
  joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  lease_expires_at TIMESTAMPTZ NOT NULL,
  left_at TIMESTAMPTZ,
  PRIMARY KEY (call_id,user_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS realtime_one_active_call_per_user
  ON realtime_call_participants(user_id) WHERE left_at IS NULL;
CREATE INDEX IF NOT EXISTS realtime_call_participants_active
  ON realtime_call_participants(call_id, left_at, lease_expires_at);

CREATE TABLE IF NOT EXISTS realtime_call_device_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  call_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  server_id TEXT NOT NULL,
  socket_id TEXT NOT NULL,
  connected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  lease_expires_at TIMESTAMPTZ NOT NULL,
  disconnected_at TIMESTAMPTZ,
  CONSTRAINT realtime_call_device_participant_fk
    FOREIGN KEY (call_id,user_id)
    REFERENCES realtime_call_participants(call_id,user_id) ON DELETE CASCADE,
  CONSTRAINT realtime_call_device_socket_uq UNIQUE (server_id,socket_id)
);
CREATE INDEX IF NOT EXISTS realtime_call_device_active
  ON realtime_call_device_sessions(call_id,user_id,lease_expires_at)
  WHERE disconnected_at IS NULL;
COMMIT;
