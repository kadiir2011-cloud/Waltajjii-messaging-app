-- Phase 54: private, durable media object metadata.
-- Draft migration. Apply only to a disposable database until separately reviewed.
BEGIN;
CREATE SCHEMA IF NOT EXISTS waltajjii;
SET LOCAL search_path = waltajjii;

CREATE TABLE IF NOT EXISTS media_objects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  bucket TEXT NOT NULL,
  object_key TEXT NOT NULL UNIQUE,
  purpose TEXT NOT NULL CHECK (purpose IN ('profile','message','group','channel','moment')),
  mime_type TEXT NOT NULL,
  file_size BIGINT NOT NULL CHECK (file_size > 0 AND file_size <= 10485760),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at TIMESTAMPTZ,
  CHECK (object_key !~ '(^/|\\.\\.|\\\\)')
);
CREATE INDEX IF NOT EXISTS idx_media_objects_owner_created
  ON media_objects(owner_id,created_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_media_objects_purpose_created
  ON media_objects(purpose,created_at DESC) WHERE deleted_at IS NULL;
COMMIT;
